function model = loadModel(path,allowUntrained)
if nargin<2, allowUntrained=false; end
if isstruct(path) && isscalar(path)
    model=path;
else
    validateattributes(path,{'char','string'},{'nonempty'},mfilename,'model');
    s=load(path,'model');
    assert(isfield(s,'model'),'S8:Model','File MAT does not contain model.');
    model=s.model;
end
assert(isfield(model,'Config') && model.Config.FormatVersion==1, ...
    'S8:Model','Unsupported model version.');
c=model.Config;
assert(c.SampleRate==8000 && c.ChunkSamples==8000 && c.Hop==320 && c.NumCodebooks==8 && c.CodebookSize==256 && c.Hop==prod(c.Strides) && ...
    mod(c.ChunkSamples,c.Hop)==0 && c.LatentDim>0 && ...
    c.NumCodebooks>=1 && c.NumCodebooks<=16 && c.NumCodebooks==fix(c.NumCodebooks) && ...
    c.BitsPerIndex>=1 && c.BitsPerIndex<=16 && ...
    c.CodebookSize==2^c.BitsPerIndex && ...
    c.Bitrate==c.SampleRate/c.Hop*c.NumCodebooks*c.BitsPerIndex && ...
    size(model.Codebooks,1)==c.LatentDim && size(model.Codebooks,2)==c.CodebookSize && ...
    size(model.Codebooks,3)==c.NumCodebooks, ...
    'S8:Model','Invalid codec dimensions or bitrate configuration.');
assert(allowUntrained || (model.TrainedSteps>0 && model.VQInitialized), ...
    'S8:Untrained','Model has not completed quantized training.');
model=s8.device(model,'cpu');
end
